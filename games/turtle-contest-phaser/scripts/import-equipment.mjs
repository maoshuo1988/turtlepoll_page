// import-equipment.mjs — 从旧版 engine.js 提取 EQUIP_POOL → TS
// apply() 闭包保留, 但只用纯数值改 fighter; 引用的外部 helper (recalcStats / applyHeal 等)
// 在 TS 层会作为 stub 注入。

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(__dirname, '../../games/turtle-battle/js/engine.js');
const OUT = resolve(__dirname, '../src/data/equipment.ts');

const code = readFileSync(SRC, 'utf8');

const start = code.indexOf('const EQUIP_POOL = [');
if (start < 0) throw new Error('EQUIP_POOL not found');
// 找到匹配的 ];
let end = start;
let depth = 0, inStr = null, escape = false;
for (let i = start; i < code.length; i++) {
  const c = code[i];
  if (escape) { escape = false; continue; }
  if (inStr) {
    if (c === '\\') escape = true;
    else if (c === inStr) inStr = null;
    continue;
  }
  if (c === '"' || c === "'" || c === '`') { inStr = c; continue; }
  if (c === '[') depth++;
  else if (c === ']') {
    depth--;
    if (depth === 0) { end = i; break; }
  }
}
let arrayLiteral = code.slice(code.indexOf('[', start), end + 1);

// apply(f) → apply(f: any), .find(b => ...) → .find((b: any) => ...)
arrayLiteral = arrayLiteral.replace(/apply\(f\)/g, 'apply(f: any)');
arrayLiteral = arrayLiteral.replace(/\.find\(b =>/g, '.find((b: any) =>');
arrayLiteral = arrayLiteral.replace(/\.filter\(b =>/g, '.filter((b: any) =>');
arrayLiteral = arrayLiteral.replace(/\.forEach\(b =>/g, '.forEach((b: any) =>');

const out = `// AUTO-GENERATED by scripts/import-equipment.mjs — DO NOT EDIT MANUALLY
// 旧版 /games/turtle-battle/js/engine.js EQUIP_POOL 镜像
// apply() 直接改 Fighter 上的数值字段; 跨文件 helper (recalcStats 等) 由本文件 stub 兜底。
/* eslint-disable @typescript-eslint/no-explicit-any */
import type { EquipmentDef, Fighter } from '../types';

// ── stub: 旧版 apply() 引用的外部 helper, PoC 阶段先 noop ────
// recalcStats: 触发数值重算 (Phase A 暂时 BattleScene 自己 recalc, 这里不动)
const recalcStats: () => void = () => {};
// 以下 helper 在装备 apply 阶段不会被调用 (运行时才用), 这里给 noop / 占位避免 ReferenceError + 类型错误
const applyHeal = (..._args: unknown[]) => 0;
const applyRawDmg = (..._args: unknown[]) => ({ hpLoss: 0, shieldAbs: 0 });
const triggerDragonFly = (_f: Fighter) => {};
const getFighterElId = (_f: Fighter) => '';
const updateHpBar = (..._args: unknown[]) => {};
const renderStatusIcons = (_f: Fighter) => {};
const applyHeal2 = (_f: Fighter, _amt: number, _opts?: unknown) => 0;

export const EQUIP_POOL: EquipmentDef[] = ${arrayLiteral} as unknown as EquipmentDef[];

export const EQUIP_BY_ID: Record<string, EquipmentDef> = Object.fromEntries(
  EQUIP_POOL.map(e => [e.id, e])
);
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out, 'utf8');

const count = (arrayLiteral.match(/\{\s*id:/g) || []).length;
console.log(`✓ Wrote ${OUT} — ${count} equipment items`);
